<?php

namespace Tests\Feature\Cda\Outputs;

use App\Models\BrandingSetting;
use App\Models\CdaReport;
use App\Models\CdaReportSnapshot;
use App\Services\Cda\Exports\ExportContent;
use App\Services\Cda\Exports\ExportContentBuilder;
use App\Services\Cda\Exports\PdfRenderer;
use App\Services\Cda\PeriodOpener;
use DOMElement;
use Dompdf\Frame;
use Dompdf\Frame\FrameTreeIterator;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Storage;
use Tests\Feature\Cda\Foundation\CdaTestHelpers;
use Tests\TestCase;
use Tests\Traits\SetupLendyPH;

/**
 * Gap round B7, from the CDA PDF browser check:
 *
 * - the footer's facts and the "Generated by Lendy" mark stay inside the page
 *   however many lines the facts wrap to (a long report name included);
 * - with no cooperative name in Settings › Branding, a live (unfinalized)
 *   export's header reads the app's name, as the other server-made documents
 *   do, never "—"; a finalized export keeps its snapshot's name.
 */
class ExportFooterAndNameTest extends TestCase
{
    use CdaTestHelpers, SetupLendyPH;

    private CdaReport $report;

    protected function setUp(): void
    {
        parent::setUp();
        $this->seedAndLogin();
        Carbon::setTestNow(Carbon::parse('2026-11-20 09:00:00', 'Asia/Manila'));
        Storage::fake('public');
        Storage::fake('private');
        $period = app(PeriodOpener::class)->ensure(2026);
        $this->report = CdaReport::query()->where('period_id', $period->id)->where('report_type', 'capr')->firstOrFail();
    }

    protected function tearDown(): void
    {
        Carbon::setTestNow();
        parent::tearDown();
    }

    public function test_the_lendy_mark_stays_inside_the_page_when_the_footer_wraps(): void
    {
        $content = $this->content();

        foreach ([$content->title, str_repeat('A very long cooperative report name ', 6)] as $title) {
            foreach (['portrait', 'landscape'] as $orientation) {
                $boxes = $this->footerBoxes($this->with($content, ['title' => $title, 'orientation' => $orientation]));
                $pageHeight = $boxes['page_height'];

                foreach (['footer-text', 'lendy-mark'] as $class) {
                    $this->assertArrayHasKey($class, $boxes, "No .{$class} element was laid out.");
                    $box = $boxes[$class];
                    $this->assertLessThanOrEqual(
                        $pageHeight - 2.0,
                        $box['y'] + $box['h'],
                        "The footer's {$class} ends below the page ({$orientation}, title of ".mb_strlen($title).' characters).',
                    );
                }
            }
        }
    }

    public function test_a_blank_branding_name_falls_back_to_the_apps_name(): void
    {
        config(['app.name' => 'Lendy.PH']);
        BrandingSetting::current()->update(['organization_name' => null]);

        $this->assertSame('Lendy.PH', $this->content()->coopName);

        BrandingSetting::current()->update(['organization_name' => '   ']);
        $this->assertSame('Lendy.PH', $this->content()->coopName);

        BrandingSetting::current()->update(['organization_name' => 'Bayanihan Cooperative']);
        $this->assertSame('Bayanihan Cooperative', $this->content()->coopName);
    }

    public function test_a_finalized_export_keeps_its_snapshots_name_and_never_takes_the_fallback(): void
    {
        config(['app.name' => 'Lendy.PH']);
        BrandingSetting::current()->update(['organization_name' => null]);

        $this->finalize(['name' => ['value' => 'Snapshot Coop']]);
        $this->assertSame('Snapshot Coop', $this->content()->coopName);

        // A snapshot frozen without a name keeps reading as it did: a dash, never today's fallback.
        $this->finalize([]);
        $this->assertSame('—', $this->content()->coopName);
    }

    /** @param  array<string, mixed>  $pulled  the snapshot's pulled profile */
    private function finalize(array $pulled): void
    {
        $snapshot = CdaReportSnapshot::query()->create([
            'report_id' => $this->report->id,
            'version' => (int) CdaReportSnapshot::query()->where('report_id', $this->report->id)->max('version') + 1,
            'template_id' => $this->report->template_id,
            'payload' => json_encode(['profile' => ['stored' => [], 'pulled' => $pulled], 'values' => []]),
            'checksum' => str_repeat('d', 64),
            'finalized_by' => $this->admin->id,
            'finalized_at' => now(),
        ]);
        $this->report->forceFill(['status' => CdaReport::STATUS_FINALIZED, 'current_snapshot_id' => $snapshot->id])->save();
    }

    private function content(): ExportContent
    {
        return app(ExportContentBuilder::class)->build($this->report->fresh(), $this->admin);
    }

    /** @param  array<string, mixed>  $changes */
    private function with(ExportContent $content, array $changes): ExportContent
    {
        return new ExportContent(...[...get_object_vars($content), ...$changes]);
    }

    /**
     * The laid-out boxes of the footer's text cell and mark on the first
     * page, read in dompdf's end-of-page callback (frames are disposed once a
     * page is drawn), with the page height in pt.
     *
     * @return array<string, mixed>
     */
    private function footerBoxes(ExportContent $content): array
    {
        $boxes = [];
        $dompdf = app(PdfRenderer::class)->prepared($content);
        $dompdf->setCallbacks([[
            'event' => 'end_page_render',
            'f' => function (Frame $page) use (&$boxes): void {
                if ($boxes !== []) {
                    return;
                }

                foreach (new FrameTreeIterator($page) as $frame) {
                    $node = $frame->get_node();

                    foreach (['footer-text', 'lendy-mark'] as $class) {
                        if (! isset($boxes[$class]) && $node instanceof DOMElement && in_array($class, explode(' ', $node->getAttribute('class')), true)) {
                            $boxes[$class] = $frame->get_border_box();
                        }
                    }
                }
            },
        ]]);
        $dompdf->render();
        $boxes['page_height'] = $dompdf->getCanvas()->get_height();

        return $boxes;
    }
}
