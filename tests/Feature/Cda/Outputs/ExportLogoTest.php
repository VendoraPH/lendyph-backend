<?php

namespace Tests\Feature\Cda\Outputs;

use App\Models\BrandingSetting;
use App\Models\CdaReport;
use App\Models\CdaReportSnapshot;
use App\Services\Cda\Exports\ExportContent;
use App\Services\Cda\Exports\ExportContentBuilder;
use App\Services\Cda\Exports\ExportLogo;
use App\Services\Cda\Exports\PdfRenderer;
use App\Services\Cda\Exports\ReportExporter;
use App\Services\Cda\PeriodOpener;
use Illuminate\Database\Events\QueryExecuted;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use RuntimeException;
use Tests\Feature\Cda\Foundation\CdaTestHelpers;
use Tests\TestCase;
use Tests\Traits\SetupLendyPH;

/**
 * The cooperative's logo in the PDF header and a "Generated by Lendy" line in
 * its footer (gap round B4, and its security review M1). The logo is Settings
 * › Branding's file on the public disk, read when a PDF is rendered (never
 * for Excel), only when its real type is PNG, JPEG or GIF, it's at most 5 MB
 * and at most 4000 px a side, and decoding it fits in the memory left. It is
 * redrawn at most 600 px tall on white as an opaque PNG data URI, so a large
 * transparent logo can't exhaust dompdf's memory. Anything else, and any
 * error while reading it, gives no logo, never a failed export.
 */
class ExportLogoTest extends TestCase
{
    use CdaTestHelpers, SetupLendyPH;

    /** A 1×1 PNG. */
    private const PNG = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';

    /** A 1×1 GIF. */
    private const GIF = 'R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';

    private CdaReport $report;

    protected function setUp(): void
    {
        parent::setUp();
        $this->seedAndLogin();
        Carbon::setTestNow(Carbon::parse('2026-11-20 09:00:00', 'Asia/Manila'));
        Storage::fake('public');
        Storage::fake('private');
        $period = app(PeriodOpener::class)->ensure(2026);
        $this->report = CdaReport::query()->where('period_id', $period->id)->where('report_type', 'capr')->firstOrFail();
    }

    protected function tearDown(): void
    {
        Carbon::setTestNow();
        parent::tearDown();
    }

    private function logo(string $path, string $bytes): void
    {
        Storage::disk('public')->put($path, $bytes);
        BrandingSetting::current()->update(['logo_path' => $path]);
    }

    private function content(): ExportContent
    {
        return app(ExportContentBuilder::class)->build($this->report->fresh(), $this->admin);
    }

    private function html(): string
    {
        return app(PdfRenderer::class)->html($this->content());
    }

    /** The PNG bytes inside the logo's data URI, or null when there is none. */
    private function logoPng(): ?string
    {
        $uri = app(ExportLogo::class)->dataUri();

        if ($uri === null) {
            return null;
        }

        $this->assertStringStartsWith('data:image/png;base64,', $uri);

        return base64_decode(substr($uri, strlen('data:image/png;base64,')), true);
    }

    /** A PNG drawn with GD: one colour, or a transparent field with an opaque square. */
    private static function drawn(int $width, int $height, bool $transparent = false): string
    {
        $image = $transparent ? imagecreatetruecolor($width, $height) : imagecreate($width, $height);

        if ($transparent) {
            imagealphablending($image, false);
            imagesavealpha($image, true);
            imagefilledrectangle($image, 0, 0, $width - 1, $height - 1, imagecolorallocatealpha($image, 0, 0, 0, 127));
            imagefilledrectangle($image, 0, 0, intdiv($width, 2), intdiv($height, 2), imagecolorallocatealpha($image, 200, 30, 30, 0));
        } else {
            imagecolorallocate($image, 20, 90, 160);
        }

        ob_start();
        imagepng($image);

        return (string) ob_get_clean();
    }

    public function test_gd_is_available_where_the_tests_run(): void
    {
        $this->assertTrue(extension_loaded('gd'), 'The logo is redrawn with GD.');
    }

    public function test_a_png_logo_shows_in_the_header_as_a_data_uri(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));

        $png = $this->logoPng();
        $this->assertNotNull($png);
        $this->assertSame([1, 1], array_slice(getimagesizefromstring($png), 0, 2), 'A small logo is never enlarged.');

        $html = $this->html();
        $this->assertStringContainsString('<img class="logo" src="data:image/png;base64,', $html);
        $this->assertStringContainsString(ExportContent::LENDY_MARK, $html);
        $this->assertStringContainsString('/Subtype /Image', app(PdfRenderer::class)->render($this->content()));
    }

    public function test_a_normal_transparent_logo_comes_out_a_smaller_opaque_png(): void
    {
        $source = self::drawn(1200, 800, true);
        $this->logo('branding/logo.png', $source);

        $png = $this->logoPng();
        $this->assertNotNull($png);
        $size = getimagesizefromstring($png);
        $this->assertSame([900, 600, 'image/png'], [$size[0], $size[1], $size['mime']], 'At most 600 px tall, the aspect kept.');

        $image = imagecreatefromstring($png);
        $corner = imagecolorsforindex($image, imagecolorat($image, 899, 599));
        $this->assertSame(['red' => 255, 'green' => 255, 'blue' => 255, 'alpha' => 0], $corner, 'The transparent part is flattened onto white.');
    }

    public function test_a_4000_px_logo_is_redrawn_600_px_tall(): void
    {
        $this->logo('branding/logo.png', self::drawn(4000, 4000));

        $png = $this->logoPng();
        $this->assertNotNull($png);
        $this->assertSame([600, 600], array_slice(getimagesizefromstring($png), 0, 2));
        $this->assertStringContainsString('/Subtype /Image', app(PdfRenderer::class)->render($this->content()), 'The PDF still renders.');
    }

    public function test_a_logo_over_4000_px_a_side_is_skipped(): void
    {
        $this->assertSame(4000, ExportLogo::MAX_SOURCE_SIDE);

        foreach ([[4001, 10], [10, 4001]] as [$width, $height]) {
            $this->logo('branding/logo.png', self::drawn($width, $height));

            $this->assertNull(app(ExportLogo::class)->dataUri(), "{$width}×{$height}");
            $this->assertStringNotContainsString('<img', $this->html());
        }
    }

    public function test_a_logo_gd_cannot_read_is_skipped(): void
    {
        $png = base64_decode(self::PNG);
        $broken = substr($png, 0, 33).str_repeat("\xAB", strlen($png) - 33);
        $this->assertNotFalse(getimagesizefromstring($broken), 'Its header still reads as a PNG.');
        $this->logo('branding/logo.png', $broken);

        $this->assertNull(app(ExportLogo::class)->dataUri());
    }

    public function test_a_gif_logo_is_accepted_by_its_real_type_whatever_its_name(): void
    {
        $this->logo('branding/logo.bin', base64_decode(self::GIF));

        $this->assertNotNull($this->logoPng());
    }

    public function test_anything_but_png_jpeg_or_gif_is_skipped(): void
    {
        $files = [
            'branding/logo.png' => 'not an image at all',
            'branding/logo.svg' => '<svg xmlns="http://www.w3.org/2000/svg"><image href="https://example.com/x.png"/></svg>',
            'branding/big.png' => base64_decode(self::PNG).str_repeat("\0", 5 * 1024 * 1024),
        ];

        foreach ($files as $path => $bytes) {
            $this->logo($path, $bytes);
            $this->assertNull(app(ExportLogo::class)->dataUri(), $path);
            $this->assertStringNotContainsString('<img', $this->html(), $path);
        }
    }

    public function test_a_path_outside_the_disk_or_a_missing_file_is_skipped(): void
    {
        foreach (['../../.env', '/etc/passwd', 'branding/missing.png', ''] as $path) {
            BrandingSetting::current()->update(['logo_path' => $path === '' ? null : $path]);
            $this->assertNull(app(ExportLogo::class)->dataUri(), $path);
        }
    }

    public function test_with_no_logo_the_footer_still_carries_the_lendy_line(): void
    {
        $html = $this->html();

        $this->assertStringNotContainsString('<img', $html);
        $this->assertStringContainsString('Generated by Lendy', $html);
    }

    public function test_each_kind_of_image_counts_its_decoding_bytes_a_pixel(): void
    {
        $this->assertSame(8, ExportLogo::bytesPerPixel(self::drawn(4, 4, true), 'image/png'), 'Truecolour PNG: GD\'s pixels plus the raw rows it reads.');
        $this->assertSame(2, ExportLogo::bytesPerPixel(self::drawn(4, 4), 'image/png'), 'Palette PNG.');
        $grey = base64_decode(self::PNG);
        $grey[25] = chr(0);
        $this->assertSame(2, ExportLogo::bytesPerPixel($grey, 'image/png'), 'Greyscale PNG.');
        $this->assertSame(1, ExportLogo::bytesPerPixel(base64_decode(self::GIF), 'image/gif'));
        $this->assertSame(4, ExportLogo::bytesPerPixel('jpeg bytes', 'image/jpeg'));
    }

    public function test_decoding_must_fit_in_the_memory_left(): void
    {
        $used = 20 * 1024 * 1024;

        $this->assertFalse(ExportLogo::fitsInMemory(4000, 4000, 8, '128M', $used), 'A 4000×4000 truecolour PNG at 128M.');
        $this->assertTrue(ExportLogo::fitsInMemory(4000, 4000, 2, '128M', $used), 'A 4000×4000 palette PNG at 128M.');
        $this->assertTrue(ExportLogo::fitsInMemory(4000, 4000, 8, '512M', $used));
        $this->assertTrue(ExportLogo::fitsInMemory(4000, 4000, 8, '-1', $used));
        $headroom = 8 * 1024 * 1024;
        $needed = (int) ceil((600 * 600 * 8 + 600 * 600 * 4 + 600 * 600 * 3) * 1.25);
        $this->assertTrue(ExportLogo::fitsInMemory(600, 600, 8, (string) ($headroom + $needed), 0), 'The source, the copy and the PNG writer\'s buffer, with a quarter more.');
        $this->assertFalse(ExportLogo::fitsInMemory(600, 600, 8, (string) ($headroom + $needed - 1), 0));
    }

    public function test_a_failing_logo_read_never_fails_the_pdf(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));
        $this->app->instance(ExportLogo::class, new class extends ExportLogo
        {
            public function dataUri(): ?string
            {
                throw new RuntimeException('The disk is gone.');
            }
        });

        $html = $this->html();

        $this->assertStringNotContainsString('<img', $html);
        $this->assertStringContainsString('Generated by Lendy', $html);
    }

    public function test_a_failing_branding_read_gives_no_logo(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));
        DB::listen(function (QueryExecuted $query): void {
            if (str_contains($query->sql, 'branding_settings')) {
                throw new RuntimeException('The branding table could not be read.');
            }
        });

        $this->assertNull(app(ExportLogo::class)->dataUri());
    }

    public function test_a_finalized_report_keeps_its_snapshot_name_and_reads_the_logo_now(): void
    {
        BrandingSetting::current()->update(['organization_name' => 'Today\'s Name']);
        $snapshot = CdaReportSnapshot::query()->create([
            'report_id' => $this->report->id,
            'version' => 1,
            'template_id' => $this->report->template_id,
            'payload' => json_encode([
                'template' => ['definition' => $this->report->template->definition, 'version' => '2026.2'],
                'profile' => ['pulled' => ['name' => 'Name at Finalize']],
                'values' => [],
            ]),
            'checksum' => str_repeat('a', 64),
            'finalized_by' => $this->admin->id,
            'finalized_at' => now(),
        ]);
        $this->report->forceFill(['status' => CdaReport::STATUS_FINALIZED, 'current_snapshot_id' => $snapshot->id])->save();
        $this->logo('branding/logo.png', base64_decode(self::PNG));

        $html = $this->html();

        $this->assertStringContainsString('Name at Finalize', $html);
        $this->assertStringNotContainsString('Today&#039;s Name', $html);
        $this->assertStringContainsString('<img class="logo" src="data:image/png;base64,', $html);
    }

    public function test_only_a_pdf_export_reads_the_logo(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));
        $logo = $this->spy(ExportLogo::class);

        app(ReportExporter::class)->export($this->report->fresh(), 'xlsx', $this->admin);
        $logo->shouldNotHaveReceived('dataUri');

        app(ReportExporter::class)->export($this->report->fresh(), 'pdf', $this->admin);
        $logo->shouldHaveReceived('dataUri')->once();
    }
}
