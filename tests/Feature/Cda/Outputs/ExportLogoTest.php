<?php

namespace Tests\Feature\Cda\Outputs;

use App\Models\BrandingSetting;
use App\Models\CdaReport;
use App\Models\CdaReportSnapshot;
use App\Services\Cda\Exports\ExportContent;
use App\Services\Cda\Exports\ExportContentBuilder;
use App\Services\Cda\Exports\PdfRenderer;
use App\Services\Cda\Exports\XlsxWriter;
use App\Services\Cda\PeriodOpener;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Storage;
use Tests\Feature\Cda\Foundation\CdaTestHelpers;
use Tests\TestCase;
use Tests\Traits\SetupLendyPH;
use ZipArchive;

/**
 * The cooperative's logo in the PDF header and a "Generated by Lendy" line in
 * its footer (gap round B4). The logo is Settings › Branding's file on the
 * public disk, read at export time, only when its real type is PNG, JPEG or
 * GIF and it's at most 5 MB, as a data URI (dompdf fetches nothing). Anything
 * else is skipped without an error.
 */
class ExportLogoTest extends TestCase
{
    use CdaTestHelpers, SetupLendyPH;

    /** A 1×1 PNG. */
    private const PNG = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNk+M9QDwADhgGAWjR9awAAAABJRU5ErkJggg==';

    /** A 1×1 GIF. */
    private const GIF = 'R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7';

    private CdaReport $report;

    protected function setUp(): void
    {
        parent::setUp();
        $this->seedAndLogin();
        Carbon::setTestNow(Carbon::parse('2026-11-20 09:00:00', 'Asia/Manila'));
        Storage::fake('public');
        $period = app(PeriodOpener::class)->ensure(2026);
        $this->report = CdaReport::query()->where('period_id', $period->id)->where('report_type', 'capr')->firstOrFail();
    }

    protected function tearDown(): void
    {
        Carbon::setTestNow();
        parent::tearDown();
    }

    private function logo(string $path, string $bytes): void
    {
        Storage::disk('public')->put($path, $bytes);
        BrandingSetting::current()->update(['logo_path' => $path]);
    }

    private function content(): ExportContent
    {
        return app(ExportContentBuilder::class)->build($this->report->fresh(), $this->admin);
    }

    public function test_a_png_logo_shows_in_the_header_as_a_data_uri(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));

        $content = $this->content();
        $this->assertSame('data:image/png;base64,'.self::PNG, $content->logoDataUri);

        $html = app(PdfRenderer::class)->html($content);
        $this->assertStringContainsString('<img class="logo" src="data:image/png;base64,'.self::PNG.'"', $html);
        $this->assertStringContainsString(ExportContent::LENDY_MARK, $html);
        $this->assertStringContainsString('/Subtype /Image', app(PdfRenderer::class)->render($content));
    }

    public function test_a_gif_logo_is_accepted_by_its_real_type_whatever_its_name(): void
    {
        $this->logo('branding/logo.bin', base64_decode(self::GIF));

        $this->assertSame('data:image/gif;base64,'.self::GIF, $this->content()->logoDataUri);
    }

    public function test_anything_but_png_jpeg_or_gif_is_skipped(): void
    {
        $files = [
            'branding/logo.png' => 'not an image at all',
            'branding/logo.svg' => '<svg xmlns="http://www.w3.org/2000/svg"><image href="https://example.com/x.png"/></svg>',
            'branding/big.png' => base64_decode(self::PNG).str_repeat("\0", 5 * 1024 * 1024),
        ];

        foreach ($files as $path => $bytes) {
            $this->logo($path, $bytes);
            $content = $this->content();
            $this->assertNull($content->logoDataUri, $path);
            $this->assertStringNotContainsString('<img', app(PdfRenderer::class)->html($content), $path);
        }
    }

    public function test_a_path_outside_the_disk_or_a_missing_file_is_skipped(): void
    {
        foreach (['../../.env', '/etc/passwd', 'branding/missing.png', ''] as $path) {
            BrandingSetting::current()->update(['logo_path' => $path === '' ? null : $path]);
            $this->assertNull($this->content()->logoDataUri, $path);
        }
    }

    public function test_with_no_logo_the_footer_still_carries_the_lendy_line(): void
    {
        $content = $this->content();

        $this->assertNull($content->logoDataUri);
        $html = app(PdfRenderer::class)->html($content);
        $this->assertStringNotContainsString('<img', $html);
        $this->assertStringContainsString('Generated by Lendy', $html);
    }

    public function test_a_finalized_report_keeps_its_snapshot_name_and_reads_the_logo_now(): void
    {
        BrandingSetting::current()->update(['organization_name' => 'Today\'s Name']);
        $snapshot = CdaReportSnapshot::query()->create([
            'report_id' => $this->report->id,
            'version' => 1,
            'template_id' => $this->report->template_id,
            'payload' => json_encode([
                'template' => ['definition' => $this->report->template->definition, 'version' => '2026.2'],
                'profile' => ['pulled' => ['name' => 'Name at Finalize']],
                'values' => [],
            ]),
            'checksum' => str_repeat('a', 64),
            'finalized_by' => $this->admin->id,
            'finalized_at' => now(),
        ]);
        $this->report->forceFill(['status' => CdaReport::STATUS_FINALIZED, 'current_snapshot_id' => $snapshot->id])->save();
        $this->logo('branding/logo.png', base64_decode(self::PNG));

        $content = $this->content();

        $this->assertSame('Name at Finalize', $content->coopName);
        $this->assertSame('data:image/png;base64,'.self::PNG, $content->logoDataUri);
    }

    public function test_the_excel_export_stays_text_only(): void
    {
        $this->logo('branding/logo.png', base64_decode(self::PNG));

        $this->assertStringNotContainsString('/xl/media/', implode('|', $this->xlsxEntries()));
    }

    /** @return list<string> */
    private function xlsxEntries(): array
    {
        $bytes = app(XlsxWriter::class)->write($this->content());
        $path = tempnam(sys_get_temp_dir(), 'xlsx');
        file_put_contents($path, $bytes);
        $zip = new ZipArchive;
        $zip->open($path);
        $names = [];

        for ($i = 0; $i < $zip->numFiles; $i++) {
            $names[] = (string) $zip->getNameIndex($i);
        }

        $zip->close();
        unlink($path);

        return $names;
    }
}
