<?php

namespace App\Services\Cda\Exports;

use Dompdf\Dompdf;
use Dompdf\Options;
use Throwable;

/**
 * A CDA report as a PDF (CDA design §9): the Blade view
 * `resources/views/cda/report.blade.php` (auto-escaped) through dompdf, on A4
 * in the template's orientation.
 *
 * dompdf runs locked down: no remote fetches, no embedded PHP, no
 * JavaScript, and its file access is chrooted to the view folder, so a value
 * in a report can never make it read a file or call out. DejaVu Sans, bundled
 * with dompdf, renders the ₱ sign. "Page X of Y" is drawn on every page after
 * layout, into the fixed footer's right column (PAGE_COLUMN_MM), which the
 * view keeps empty; the footer's facts wrap in the left column, so the two
 * never run into each other.
 *
 * Not final, so a test can stand in for it (the export race test).
 */
class PdfRenderer
{
    public const FONT = 'DejaVu Sans';

    /** The page's right margin (the view's `@page`), in mm. */
    public const MARGIN_RIGHT_MM = 14;

    /**
     * The page's bottom margin (the view's `@page`), in mm. dompdf pins the
     * fixed footer's top (MARGIN_BOTTOM_MM - FOOTER_DROP_MM = 20 mm above the
     * page's edge) and lets it grow downward, so that room holds the footer's
     * facts on up to four lines plus the "Generated by Lendy" mark (about
     * 10 pt a line) inside the page (gap round B7: two lines plus the mark
     * used to run off it).
     */
    public const MARGIN_BOTTOM_MM = 24;

    /** How far the fixed footer sits below the content, into the bottom margin, in mm. */
    public const FOOTER_DROP_MM = 4;

    /** The footer's right column, kept empty for "Page X of Y", in mm. */
    public const PAGE_COLUMN_MM = 32;

    private const PT_PER_MM = 72 / 25.4;

    /**
     * The export as HTML, with the cooperative's logo read now (ExportLogo,
     * from the container, so a stand-in renderer keeps its own constructor):
     * only a PDF ever reads the logo, and a logo problem never fails the
     * export (no logo instead).
     */
    public function html(ExportContent $content): string
    {
        try {
            $logo = app(ExportLogo::class)->dataUri();
        } catch (Throwable $e) {
            report($e);
            $logo = null;
        }

        return view('cda.report', ['content' => $content, 'logo' => $logo])->render();
    }

    public function render(ExportContent $content): string
    {
        $dompdf = $this->prepared($content);
        $dompdf->render();

        $canvas = $dompdf->getCanvas();
        $font = $dompdf->getFontMetrics()->getFont(self::FONT);
        $x = $canvas->get_width() - (self::MARGIN_RIGHT_MM + self::PAGE_COLUMN_MM - 2) * self::PT_PER_MM;
        $y = $canvas->get_height() - (self::MARGIN_BOTTOM_MM - self::FOOTER_DROP_MM) * self::PT_PER_MM;
        $canvas->page_text($x, $y, 'Page {PAGE_NUM} of {PAGE_COUNT}', $font, 7, [0.32, 0.38, 0.43]);

        return (string) $dompdf->output();
    }

    /**
     * The document loaded on its paper, locked down, not yet rendered: what
     * render() lays out, and where a test hooks dompdf's page callbacks to
     * read the laid-out footer.
     */
    public function prepared(ExportContent $content): Dompdf
    {
        $options = new Options;
        $options->setIsRemoteEnabled(false);
        $options->setIsPhpEnabled(false);
        $options->setIsJavascriptEnabled(false);
        $options->setDefaultFont(self::FONT);
        $options->setChroot([resource_path('views/cda')]);
        $options->setTempDir(sys_get_temp_dir());
        $options->setFontCache($this->fontCache());

        $dompdf = new Dompdf($options);
        $dompdf->loadHtml($this->html($content), 'UTF-8');
        $dompdf->setPaper('A4', $content->orientation);

        return $dompdf;
    }

    /**
     * Where dompdf keeps its parsed font metrics: the framework cache, which
     * php-fpm can write (vendor/ may not be). dompdf only writes there when
     * the folder is writable, and otherwise re-reads the bundled metrics.
     */
    private function fontCache(): string
    {
        $path = storage_path('framework/cache/dompdf');

        if (! is_dir($path)) {
            @mkdir($path, 0775, true);
        }

        return $path;
    }
}
